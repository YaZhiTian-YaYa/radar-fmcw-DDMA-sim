%% ========================================================================
%  runCases.m —— 批量案例生成: 每个案例一个"案例N"文件夹
%  内容: ① 结果图(跳过天线 4 张与 RCS 1 张) ② rawdata.mat(ADC 原始数据+场景真值+
%        全部链路参数, 内含 readme 字段说明存放规则) ③ caseSummary.txt(人读摘要)
%  场景: genPairScene 随机多案例(OMP型/DML型对+单目标), weakFrac 控制弱目标占比
%        (压 RCS 5~15dB → 制造低信噪比案例, 考核 OMP/DML 性能下限, 允许漏检)。
%  运行: matlab -batch "run('runCases.m')" (每案例约 1.5 分钟)
%  ========================================================================
close all;
% 批量状态存 batchState(main_sim 的 clear 会保留它, 循环变量借此延续)。
% 已预置 batchState 时(如 runCasesLowSNR.m 注入低信噪比批次)直接沿用, 不覆盖。
if ~exist('batchState', 'var') || ~isfield(batchState, 'snrOff')
batchState = struct('idx', 1, 'nCases', 8, ...
    'seeds',    [1001 1002 1003 1004 1005 1006 1007 1008], ...
    'weakFrac', [0    0.2  0.35 0.5  0.25 0.4  0.15 0.3 ], ...
    'snrOff',   [0    0    0    0    0    0    0    0   ], ...   % 全场 RCS 压低(dB): 常规批为 0
    'nOmp', 8, 'nDml', 6, 'nSingle', 14, ...          % 稀疏十字路口风格: 14对+14单目标, RD 平面强制间隔
    'root',     pwd);
end

while batchState.idx <= batchState.nCases
    c = batchState.idx;
    caseDir = fullfile(batchState.root, sprintf('案例%d', c));
    if ~exist(caseDir, 'dir'), mkdir(caseDir); end

    % ---- 本案例场景 + 钩子(静态图与校准遍图不存; 图存到案例文件夹) ----
    % 跳过: 天线6张(每案例相同) + 校准遍7张 fig12~18(校准场景固定为仅角反,
    % 每案例相同, 校准结果经 cCal/rcsCfg 进入处理链) + RCS 图 fig33。
    [targetsOverride, truth] = genPairScene(batchState.seeds(c), batchState.nOmp, ...
                                            batchState.nDml, batchState.nSingle, ...
                                            batchState.weakFrac(c), batchState.snrOff(c));
    saveFigDir = caseDir;
    skipFigs = {'fig1_AntPat_TX.png','fig2_AntPat_RX.png','fig3_AntPatCut_TX.png', 'fig4_AntPatCut_RX.png', ...
                'fig5_AntPatPh_TX.png','fig6_AntPatPh_RX.png', ...
                'fig13_ADC_time_cal.png','fig14_RD_8RX_cal.png','fig15_RD_surf_cal.png', ...
                'fig16_NoiseFloor_cal.png','fig17_NoiseFloor_med_cal.png','fig18_CalibCheck.png', ...
                'fig19_RCSCalib.png','fig35_RCS.png','fig12_FilterChain.png'};
    saveDBFStage = '';                                       % 案例不需要 DBF 快照
    fprintf('======== 案例 %d/%d (种子 %d, 弱目标占比 %.0f%%, 全场RCS压低 %d dB) ========\n', ...
            c, batchState.nCases, batchState.seeds(c), 100*batchState.weakFrac(c), ...
            batchState.snrOff(c));
    evalc('main_sim;');                                      % 全链路(输出吞掉, 案例摘要单独写)
    % main_sim 的 clear 清掉了局部变量 → 从 batchState 重推导, 真值按种子确定性重生成
    c = batchState.idx;
    caseDir = fullfile(batchState.root, sprintf('案例%d', c));
    [~, truth] = genPairScene(batchState.seeds(c), batchState.nOmp, ...
                              batchState.nDml, batchState.nSingle, ...
                              batchState.weakFrac(c), batchState.snrOff(c));

    % ---- rawdata.mat: ADC 原始数据 + 场景真值 + 全部链路参数(readme 含存放规则) ----
    raw = struct();
    raw.adcRawData = adcRawData;      % [nSamples×nChirps×nRX] int16 口径实采样 counts
    raw.prm         = prm;            % 波形参数(fs/B/Ts/Tc/cr/fStart/nGroups)
    raw.dims        = dims;           % 公共维度(rngPts/nV/dopBinNum/.../DeltaR/Vres)
    raw.targets     = targets;        % 场景真值(结构体数组, 字段见 readme)
    raw.truth       = truth;          % 案例对/单目标真值表(genPairScene 输出, 便于对账)
    raw.encodeSeq   = encodeSeq;      % DDMA 编码(16 槽)
    raw.ddmShift    = ddmShift;       % 各 TX 的 DDMA 码槽位(0 起)
    raw.TX_A        = TX_A;           raw.RX_A = RX_A;     % TX/RX 通道幅度差(线性)
    raw.antenna_t   = antenna_t;      raw.antenna_r = antenna_r;  % 居中后坐标 (m, [3×8])
    raw.FFT_d0      = FFT_d0;         raw.lambda = lambda;
    raw.rfInfo      = rfInfo;         % 逐目标 IF 滤形增益(RCS 标定用, 算法工程师不可见)
    raw.readme = sprintf([ ...
        '案例 rawdata 存放规则(详细版见工程目录《案例RawData数据说明.docx》)\n' ...
        '1. adcRawData [nSamples=1024 × nChirps=512 × nRX=8], int16 口径实采样 counts:\n' ...
        '   dim1=快时间(ADC 实采样 60 MHz, 每 chirp 1024 点); dim2=chirp 序号(帧内 512);\n' ...
        '   dim3=RX 通道 1..8。每个 chirp 内已是 8 个 TX 的 DDMA 叠加信号。\n' ...
        '   ADC 位数为 16bit(射频模块内 adcBits 旋钮; 数据 2 字节 int16, 若改非 16bit\n' ...
        '   会左移补齐, 存储_LSB = 满量程/2^15, 约定见 rf_sim_core"ADC 整数量化"段)。\n' ...
        '2. 波形: 起始频率 prm.fStart, chirp 带宽 prm.B(采样窗内), 周期 prm.Tc,\n' ...
        '   步进频占比 prm.cr(全帧占用 (1+cr)·B)。实采样 → 距离维 FFT 取前 nV=513 bin。\n' ...
        '3. targets 真值字段: gate_R=距离 bin(×dims.DeltaR→米); gate_D=法向速度 bin\n' ...
        '   (可超 512, 谱线折叠); azi/ele=方位/俯仰角(deg); rcsDb(dBsm); vTan=切向速度(m/s,\n' ...
        '   不产生多普勒); isCorner=1 为 0° 校准角反(目标1)。\n' ...
        '4. 谱线实际位置 ≈ mod(gate_D + gate_R, 512)(步进频耦合约每距离 bin +1 个多普勒 bin)。\n' ...
        '   法向速度 = gate_D × dims.Vres; 同对目标的 gate_D 可能相差 512 的整数倍(n=1 同 bin)。\n' ...
        '5. truth 真值表: cell=[gate_R, 谱线bin](0起); type: 1=OMP型对(角差≥5°) 2=DML型对\n' ...
        '   (1.5~6°) 0=单目标(考核误分裂); az1/az2/rcs1/rcs2=两成员角度与RCS(单目标 az2=NaN)。\n' ...
        '   本案例弱目标占比 weakFrac=%.0f%%(弱成员被压 5~15dB, 部分目标应故意漏检)。\n' ...
        '6. 阵列: antenna_t/antenna_r 为居中后物理坐标(m); FFT_d0=阵元间距; lambda=波长;\n' ...
        '   虚拟通道顺序 TX 内循环/RX 外循环(64 通道), 方位最长行 36 通道取 rowLut(需重算)。\n'], ...
        100*batchState.weakFrac(c));
    save(fullfile(caseDir, 'rawdata.mat'), '-struct', 'raw');

    % ---- 数据说明.txt: rawdata 存放规则随文件夹落地一份(不打开 mat 也能看) ----
    fidTxt = fopen(fullfile(caseDir, '数据说明.txt'), 'w', 'n', 'UTF-8');
    fprintf(fidTxt, '%s', raw.readme);
    fclose(fidTxt);

    % ---- caseSummary.txt: 人读摘要(真值表 + 本案例模块结果) ----
    fid = fopen(fullfile(caseDir, 'caseSummary.txt'), 'w', 'n', 'UTF-8');
    fprintf(fid, '案例 %d: 种子 %d, 弱目标占比 %.0f%%, 全场RCS压低 %d dB(角反除外), 目标 %d 个(校准遍角反 1 + 目标遍 %d: %d对+%d单目标; 稀疏十字路口风格)\n\n', ...
            c, batchState.seeds(c), 100*batchState.weakFrac(c), batchState.snrOff(c), numel(targets)+1, ...
            numel(targets), batchState.nOmp + batchState.nDml, batchState.nSingle);
    fprintf(fid, '真值表(谱线bin为0起且四舍五入到整数bin, type: 1=OMP型 2=DML型 0=单目标):\n');
    fprintf(fid, '%4s %6s %8s %8s %8s %8s %7s\n', 'type', 'R', 'D谱线', 'az1', 'az2', 'rcs1', 'rcs2');
    for q = 1:numel(truth)
        fprintf(fid, '%4d %6d %8.0f %8.1f %8.1f %8.1f %8.1f\n', truth(q).type, truth(q).cell(1), ...
                round(truth(q).cell(2)), truth(q).az1, truth(q).az2, truth(q).rcs1, truth(q).rcs2);
    end
    fprintf(fid, '\n模块结果: CFAR 确认 %d 点 | OMP 第二目标 %d 个(删 %d) | DML 第二目标 %d 个 | 最终点云 %d 点\n', ...
            numel(stageDbf.azi), ompCfg.n2nd, ompCfg.n2ndDrop, dmlCfg.nDML2nd, numel(tgtOut));
    fclose(fid);

    fprintf('案例 %d 完成: %s (%d 图 + rawdata.mat + caseSummary.txt)\n', ...
            c, caseDir, 35 - numel(skipFigs));
    batchState.idx = c + 1;                                  % 推进(main_sim 不清 batchState)
end
clear batchState targetsOverride saveFigDir skipFigs saveDBFStage   % 清钩子, 防影响日常运行
fprintf('======== 本批案例全部生成完毕 ========\n');
